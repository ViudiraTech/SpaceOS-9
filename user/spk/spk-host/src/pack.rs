use std::collections::BTreeMap;
use std::fs::{self, File};
use std::io::{self, Write};
use std::os::unix::fs::MetadataExt;
use std::path::{Path, PathBuf};

use spk_core::archive::{inspect_spk, MAX_META_SIZE};
use spk_core::fsutil::{atomic_write, sha256_bytes, sha256_file};
use spk_core::manifest::{
    format_mode, parse_mode, strip_special_bits, validate_relative_path, validate_symlink_target,
    FileType, Manifest, PackageFile, META_BUILDINFO, META_CHANGELOG, META_INSTALL,
};
use spk_core::{Error, Result};

pub struct PackResult {
    pub output: PathBuf,
    pub filename: String,
    pub sha256: String,
    pub size: u64,
    pub manifest: Manifest,
    pub warnings: Vec<String>,
}

#[derive(Clone, Debug)]
struct SourceEntry {
    rel: String,
    abs: PathBuf,
    kind: FileType,
    mode: u32,
    size: u64,
    sha256: String,
    target: Option<String>,
}

/// Pack `staging` according to `manifest_path`. The manifest may either list
/// files explicitly (they are then verified against the tree) or leave the
/// `files` table empty (it is generated by scanning the tree).
pub fn pack(manifest_path: &Path, staging: &Path, output: &Path, level: i32) -> Result<PackResult> {
    if !(1..=22).contains(&level) {
        return Err(Error::Package(format!(
            "zstd level {level} is outside 1..=22"
        )));
    }
    let mut manifest = Manifest::load(manifest_path)?;
    let meta_dir = manifest_path
        .parent()
        .ok_or_else(|| Error::Manifest("manifest path has no parent directory".into()))?;

    let source_date_epoch = source_date_epoch()?;
    if manifest.build_date == 0 {
        manifest.build_date = source_date_epoch.unwrap_or(0);
    }
    let mtime = source_date_epoch.unwrap_or(manifest.build_date);

    let meta = read_meta_files(meta_dir, staging, &manifest)?;
    let (mut sources, warnings) = walk_staging(staging, &manifest)?;
    sources.sort_by(|a, b| a.rel.cmp(&b.rel));

    let generated = package_files(&sources);
    if !manifest.files.is_empty() {
        verify_declared_files(&manifest, &generated)?;
    }
    manifest.files = generated;
    manifest.validate()?;

    let manifest_toml = manifest.to_toml()?;
    let tar = build_tar(&manifest_toml, &meta, &sources, mtime)?;
    let compressed = compress(&tar, level)?;

    let filename = manifest.package_filename();
    let output = resolve_output(output, &filename)?;
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent)?;
    }
    atomic_write(&output, &compressed, 0o644)?;

    let inspected = inspect_spk(&output)?;
    if inspected.manifest.to_toml()? != manifest_toml {
        return Err(Error::Package(
            "packed manifest does not round-trip; internal error".into(),
        ));
    }

    Ok(PackResult {
        output,
        filename,
        sha256: inspected.package_sha256,
        size: inspected.package_size,
        manifest,
        warnings,
    })
}

fn source_date_epoch() -> Result<Option<u64>> {
    match std::env::var("SOURCE_DATE_EPOCH") {
        Ok(text) => {
            let epoch = text
                .parse::<u64>()
                .map_err(|_| Error::Package(format!("invalid SOURCE_DATE_EPOCH '{text}'")))?;
            Ok(Some(epoch))
        }
        Err(std::env::VarError::NotPresent) => Ok(None),
        Err(e) => Err(Error::Package(format!("SOURCE_DATE_EPOCH: {e}"))),
    }
}

fn read_meta_files(
    meta_dir: &Path,
    staging: &Path,
    manifest: &Manifest,
) -> Result<BTreeMap<&'static str, Vec<u8>>> {
    let mut meta = BTreeMap::new();
    for name in [META_BUILDINFO, META_CHANGELOG] {
        if let Some(data) = read_optional_regular(&meta_dir.join(name), name)? {
            meta.insert(name, data);
        }
    }
    // .INSTALL lives at the package root (staging root); older layouts kept it
    // beside the manifest, so accept that as a fallback.
    let install = read_optional_regular(&staging.join(META_INSTALL), META_INSTALL)?.or(
        read_optional_regular(&meta_dir.join(META_INSTALL), META_INSTALL)?,
    );
    if let Some(data) = install {
        meta.insert(META_INSTALL, data);
    }
    if !manifest.scripts && meta.contains_key(META_INSTALL) {
        return Err(Error::Manifest(
            "manifest declares scripts = false but .INSTALL is present".into(),
        ));
    }
    Ok(meta)
}

fn read_optional_regular(path: &Path, name: &str) -> Result<Option<Vec<u8>>> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(e.into()),
    };
    if !metadata.file_type().is_file() {
        return Err(Error::Manifest(format!("{name} must be a regular file")));
    }
    if metadata.len() > MAX_META_SIZE {
        return Err(Error::Manifest(format!(
            "{name} exceeds {MAX_META_SIZE} bytes"
        )));
    }
    Ok(Some(fs::read(path)?))
}

fn walk_staging(root: &Path, manifest: &Manifest) -> Result<(Vec<SourceEntry>, Vec<String>)> {
    let metadata = fs::symlink_metadata(root)?;
    if !metadata.file_type().is_dir() {
        return Err(Error::Package(format!(
            "staging root {} is not a directory",
            root.display()
        )));
    }
    let mut entries = Vec::new();
    let mut warnings = Vec::new();
    walk_dir(
        root,
        root,
        manifest.allow_setuid,
        &mut entries,
        &mut warnings,
    )?;
    Ok((entries, warnings))
}

fn walk_dir(
    root: &Path,
    dir: &Path,
    allow_setuid: bool,
    entries: &mut Vec<SourceEntry>,
    warnings: &mut Vec<String>,
) -> Result<()> {
    let mut children: Vec<_> = fs::read_dir(dir)?.collect::<io::Result<Vec<_>>>()?;
    children.sort_by_key(|entry| entry.file_name());
    for child in children {
        let abs = child.path();
        let metadata = fs::symlink_metadata(&abs)?;
        let relative = abs
            .strip_prefix(root)
            .map_err(|_| Error::Package(format!("{} escapes the staging root", abs.display())))?;
        let rel = relative.to_str().ok_or_else(|| {
            Error::Package(format!("non-UTF-8 path in staging: {}", abs.display()))
        })?;
        let rel = rel.replace(std::path::MAIN_SEPARATOR, "/");
        if !rel.contains('/')
            && matches!(rel.as_str(), META_INSTALL | META_CHANGELOG | META_BUILDINFO)
        {
            continue;
        }
        validate_relative_path(&rel)?;

        let file_type = metadata.file_type();
        if file_type.is_dir() {
            let mode = strip_special_bits(metadata.mode() & 0o7777, allow_setuid);
            entries.push(SourceEntry {
                rel: rel.clone(),
                abs: abs.clone(),
                kind: FileType::Dir,
                mode,
                size: 0,
                sha256: String::new(),
                target: None,
            });
            walk_dir(root, &abs, allow_setuid, entries, warnings)?;
        } else if file_type.is_file() {
            if metadata.nlink() > 1 {
                warnings.push(format!(
                    "{rel}: hard-linked staging file is stored as a regular file (P2)"
                ));
            }
            let mode = strip_special_bits(metadata.mode() & 0o7777, allow_setuid);
            entries.push(SourceEntry {
                rel: rel.clone(),
                abs: abs.clone(),
                kind: FileType::File,
                mode,
                size: metadata.len(),
                sha256: sha256_file(&abs)?,
                target: None,
            });
        } else if file_type.is_symlink() {
            let target = fs::read_link(&abs)?;
            let target = target
                .to_str()
                .ok_or_else(|| Error::Package(format!("{rel}: non-UTF-8 symlink target")))?;
            validate_symlink_target(&format!("/{rel}"), target)?;
            let target = target.to_string();
            entries.push(SourceEntry {
                rel: rel.clone(),
                abs: abs.clone(),
                kind: FileType::Symlink,
                mode: metadata.mode() & 0o7777,
                size: target.len() as u64,
                sha256: sha256_bytes(target.as_bytes()),
                target: Some(target),
            });
        } else {
            return Err(Error::Package(format!(
                "{rel}: devices, FIFOs and sockets cannot be packaged"
            )));
        }
    }
    Ok(())
}

fn package_files(entries: &[SourceEntry]) -> Vec<PackageFile> {
    entries
        .iter()
        .map(|entry| PackageFile {
            path: format!("/{}", entry.rel),
            file_type: entry.kind,
            mode: format_mode(entry.mode),
            uid: 0,
            gid: 0,
            sha256: entry.sha256.clone(),
            size: entry.size,
            target: entry.target.clone(),
        })
        .collect()
}

fn verify_declared_files(manifest: &Manifest, generated: &[PackageFile]) -> Result<()> {
    let declared: BTreeMap<&str, &PackageFile> = manifest
        .files
        .iter()
        .map(|file| (file.path.as_str(), file))
        .collect();
    if declared.len() != generated.len() {
        return Err(Error::Manifest(format!(
            "manifest lists {} files, staging contains {}",
            declared.len(),
            generated.len()
        )));
    }
    for file in generated {
        let Some(expected) = declared.get(file.path.as_str()) else {
            return Err(Error::Manifest(format!(
                "{} is present in staging but missing from the manifest",
                file.path
            )));
        };
        if expected.file_type != file.file_type {
            return Err(Error::Manifest(format!(
                "{}: manifest type does not match staging",
                file.path
            )));
        }
        if parse_mode(&expected.mode)? != parse_mode(&file.mode)? {
            return Err(Error::Manifest(format!(
                "{}: manifest mode {} does not match staging {}",
                file.path, expected.mode, file.mode
            )));
        }
        if expected.uid != file.uid || expected.gid != file.gid {
            return Err(Error::Manifest(format!(
                "{}: manifest owner does not match staging",
                file.path
            )));
        }
        if expected.size != file.size || expected.sha256 != file.sha256 {
            return Err(Error::Manifest(format!(
                "{}: contents do not match the manifest",
                file.path
            )));
        }
        if expected.target != file.target {
            return Err(Error::Manifest(format!(
                "{}: symlink target does not match the manifest",
                file.path
            )));
        }
    }
    Ok(())
}

fn build_tar(
    manifest_toml: &str,
    meta: &BTreeMap<&'static str, Vec<u8>>,
    sources: &[SourceEntry],
    mtime: u64,
) -> Result<Vec<u8>> {
    let mut builder = tar::Builder::new(Vec::new());
    append_bytes(
        &mut builder,
        "manifest.toml",
        manifest_toml.as_bytes(),
        mtime,
    )?;
    for (name, data) in meta {
        append_bytes(&mut builder, name, data, mtime)?;
    }
    for entry in sources {
        match entry.kind {
            FileType::Dir => {
                let mut header = header(tar::EntryType::Directory, entry.mode, 0, mtime);
                builder.append_data(&mut header, &entry.rel, io::empty())?;
            }
            FileType::File => {
                let mut header = header(tar::EntryType::Regular, entry.mode, entry.size, mtime);
                let file = File::open(&entry.abs)?;
                builder.append_data(&mut header, &entry.rel, file)?;
            }
            FileType::Symlink => {
                let mut header = header(tar::EntryType::Symlink, entry.mode, 0, mtime);
                let target = entry.target.as_deref().ok_or_else(|| {
                    Error::Package(format!("{}: missing symlink target", entry.rel))
                })?;
                builder.append_link(&mut header, &entry.rel, target)?;
            }
        }
    }
    builder.finish()?;
    builder
        .into_inner()
        .map_err(|e| Error::Package(format!("finishing tar: {e}")))
}

fn header(entry_type: tar::EntryType, mode: u32, size: u64, mtime: u64) -> tar::Header {
    let mut header = tar::Header::new_gnu();
    header.set_entry_type(entry_type);
    header.set_mode(mode & 0o7777);
    header.set_uid(0);
    header.set_gid(0);
    header.set_mtime(mtime);
    header.set_size(size);
    header
}

fn append_bytes(
    builder: &mut tar::Builder<Vec<u8>>,
    path: &str,
    data: &[u8],
    mtime: u64,
) -> Result<()> {
    let mut header = header(tar::EntryType::Regular, 0o644, data.len() as u64, mtime);
    builder.append_data(&mut header, path, data)?;
    Ok(())
}

fn compress(tar: &[u8], level: i32) -> Result<Vec<u8>> {
    let mut encoder = zstd::stream::write::Encoder::new(Vec::new(), level)
        .map_err(|e| Error::Package(format!("zstd encoder: {e}")))?;
    encoder
        .write_all(tar)
        .map_err(|e| Error::Package(format!("zstd compression: {e}")))?;
    encoder
        .finish()
        .map_err(|e| Error::Package(format!("zstd compression: {e}")))
}

fn resolve_output(output: &Path, filename: &str) -> Result<PathBuf> {
    let is_dir = output.is_dir()
        || output
            .as_os_str()
            .to_string_lossy()
            .ends_with(std::path::MAIN_SEPARATOR);
    let resolved = if is_dir {
        output.join(filename)
    } else {
        output.to_path_buf()
    };
    let actual = resolved
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("");
    if actual != filename {
        return Err(Error::Package(format!(
            "output file must be named '{filename}', got '{actual}'"
        )));
    }
    Ok(resolved)
}
